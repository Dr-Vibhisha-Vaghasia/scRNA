##Filter Cells##
#Filters Poor-Quality cells.
#Rule 1: nFeature_RNA >200
#Remove cells expressing very few genes. Usually dead cells.
#Rule 2: nFeature_RNA <2500
#Remove possible doublets.Doublets occur when two cells are captured together.
#Rule 3 percent.mt <5
#Remove damaged cells.

data_filter <- subset(
  pbmc,
  subset = nFeature_RNA > 200 &
    nFeature_RNA < 2500 &
    percent.mt < 5
)

#Visualize QC After Filtering
#Confirms that poor-quality cells have been removed.
VlnPlot(
  data_filter,
  features = c("nFeature_RNA", "nCount_RNA", "percent.mt"),
  ncol = 3
)

###############################
# Normalize the data
#Why Normalize?
#Different cells contain different sequencing depths.
#Example: Cell	Reads
#           A	  6000
#           B	  12000
#Without normalization, Cell B appears to express more genes simply because it has more reads.
#LogNormalize: Formula: Normalized Count=log(Total Counts/Gene Count​ ×10000+1)
#This makes cells comparable.
#scale.factor = 10000, Each cell is scaled to 10,000 counts before log transformation.

data_norm <- NormalizeData(
  data_filter,
  normalization.method = "LogNormalize",
  scale.factor = 10000
)

### Identify highly variable genes
#Purpose: Find genes showing the greatest biological variation across cells.
#selection.method = "vst", Variance Stabilizing Transformation.
#Removes technical noise and selects biologically informative genes.
#nfeatures = 2000, Chooses the top 2,000 most variable genes.
#These genes are used later for: PCA, UMAP, t-SNE, Clustering

data_hv <- FindVariableFeatures(
  data_norm,
  selection.method = "vst",    # Variance stabilizing transformation
  nfeatures = 2000             # Number of features to select
)

#######Get Top 10 Variable Genes#####
#Returns the first ten highly variable genes
top10 <- head(VariableFeatures(data_hv), 10)
print(top10)

#Plot variable features
#Creates a scatter plot.
#X-axis: Average expression
#Y-axis: Standardized variance
#Each dot represents one gene.
