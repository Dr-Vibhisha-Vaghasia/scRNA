#Calculate percentage of mitichondrial gene expression in every cell.
#Human mitochondrial genes begin with MT
#^ = starts with
#MT- = mitochondrial genes
#Why calculate mitochondrial percentage?
#Cells with damaged membranes leak RNA.
#These cells contain relatively more mitochondrial RNA.
#High mitochondrial percentage indicates
#stressed cells
#dying cells
#damaged cells
#Example Cell A
#Total UMIs = 10000
#Mitochondrial UMIs = 300
#300/10000 ×100 = 3%, Good quality.
#Cell B=  40%, Likely dying.

#Shows metadata
